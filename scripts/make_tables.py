"""Comparison tables: traditional vs proposed, for every parameter (Required add-on 3).

    python scripts/make_tables.py

Writes
  results/comparison_all_methods.csv   every method x dataset x metric
  results/comparison_summary.csv       best traditional vs predictive, per dataset
  results/gain_decomposition.csv       how much of the gain is "headroom" vs "prediction"
  results/comparison_tables.md         the same, as Markdown for the report
"""

from __future__ import annotations

import _bootstrap  # noqa: F401  (adds src/ to sys.path)

import json

import pandas as pd

from bwalloc.config import RESULTS_DIR
from bwalloc.style import DATASET_LABELS, METHOD_ORDER

METRICS = {
    "jain": ("Jain's index", "higher"),
    "utilization": ("Utilization", "higher"),
    "unmet_frac": ("Unmet demand (share)", "lower"),
    "starvation": ("Starvation rate", "lower"),
    "stranded_frac": ("Stranded capacity (share of C)", "lower"),
    "wasted_frac": ("Over-allocation (share of C)", "lower"),
    "min_satisfaction": ("Worst-user satisfaction", "higher"),
    "alloc_ms_per_window": ("Allocation time (ms/window)", "lower"),
}
TRADITIONAL = ["Round Robin", "Max-Min Fairness", "Proportional Share"]
PROPOSED = "Predictive (Prop.)"


def main() -> None:
    summary = json.loads((RESULTS_DIR / "run_summary.json").read_text())
    names = [d for d in summary["config"]["datasets"] if d in summary["datasets"]]

    all_rows, summ_rows, decomp_rows = [], [], []
    for name in names:
        s = pd.read_csv(RESULTS_DIR / name / "allocation_summary.csv", index_col=0)
        s = s.reindex([m for m in METHOD_ORDER if m in s.index])
        hold = pd.read_csv(RESULTS_DIR / name / "holdout_forecast_metrics.csv", index_col=0)
        best_model = summary["datasets"][name]["best_model"]
        for m, r in s.iterrows():
            all_rows.append({"dataset": name, "method": m, "family": r["family"],
                             **{k: r[k] for k in METRICS}})

        # "best traditional" = traditional method with the highest Jain index
        bt = s.loc[TRADITIONAL, "jain"].idxmax()
        for k, (label, better) in METRICS.items():
            trad, prop, orc = s.loc[bt, k], s.loc[PROPOSED, k], s.loc["Oracle (Prop.)", k]
            delta = prop - trad
            improved = delta > 0 if better == "higher" else delta < 0
            summ_rows.append({"dataset": name, "metric": label, "best_traditional": bt,
                              "traditional": trad, "predictive": prop, "oracle": orc,
                              "change": delta, "better_is": better, "predictive_wins": improved})

        # Decomposition of the Jain gain:  traditional -> +headroom -> +prediction -> oracle
        j = s["jain"]
        decomp_rows.append({
            "dataset": name,
            "forecast_model": best_model,
            "forecast_NMAE": hold.loc[best_model, "NMAE"],
            "forecast_gain_vs_last_%": hold.loc[best_model, "improvement_vs_last_%"],
            "jain_proportional": j["Proportional Share"],
            "jain_reactive_headroom": j["Reactive Prop. + headroom"],
            "jain_predictive": j[PROPOSED],
            "jain_oracle": j["Oracle (Prop.)"],
            "gain_from_headroom": j["Reactive Prop. + headroom"] - j["Proportional Share"],
            "gain_from_prediction": j[PROPOSED] - j["Reactive Prop. + headroom"],
            "gap_to_oracle": j["Oracle (Prop.)"] - j[PROPOSED],
        })

    all_df = pd.DataFrame(all_rows)
    summ = pd.DataFrame(summ_rows)
    decomp = pd.DataFrame(decomp_rows)
    all_df.to_csv(RESULTS_DIR / "comparison_all_methods.csv", index=False)
    summ.to_csv(RESULTS_DIR / "comparison_summary.csv", index=False)
    decomp.to_csv(RESULTS_DIR / "gain_decomposition.csv", index=False)

    lines = ["# Traditional vs proposed – comparison tables", "",
             "_Generated by `scripts/make_tables.py` from `results/`. "
             f"Data source per dataset: "
             + ", ".join(f"{n}={summary['datasets'][n]['source']}" for n in names) + "._", ""]
    for name in names:
        lines += [f"## {DATASET_LABELS.get(name, name)}", ""]
        t = all_df[all_df["dataset"] == name].set_index("method")[list(METRICS)]
        t.columns = [METRICS[c][0] for c in t.columns]
        lines += [t.to_markdown(floatfmt=".3f"), ""]
    lines += ["## Where does the predictive gain come from? (Jain's index)", "",
              decomp.set_index("dataset").to_markdown(floatfmt=".3f"), "",
              "`gain_from_headroom`: Proportional Share -> same rule but always handing out all of C "
              "(reactive, no forecast).  \n`gain_from_prediction`: that -> the same rule fed with the "
              "forecast.  \n`gap_to_oracle`: what a perfect forecast would still add.", ""]
    (RESULTS_DIR / "comparison_tables.md").write_text("\n".join(lines))
    print(decomp.round(3).to_string())


if __name__ == "__main__":
    main()
